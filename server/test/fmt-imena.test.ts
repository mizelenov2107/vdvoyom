// Падежи имён в интерфейсе (web/src/fmt.ts). 11.10.2026: тост «Теперь вы вдвоём с Артём» —
// творительный падеж, а где окончание ничего не говорит, — null и фраза без склонения.
import { test } from "node:test";
import assert from "node:assert/strict";
import { accusative, dative, genitive, instrumental } from "../../web/src/fmt.ts";

test("творительный: типичные имена", () => {
  const cases: [string, string][] = [
    ["Артём", "Артёмом"], ["Миша", "Мишей"], ["Аня", "Аней"], ["Илья", "Ильёй"], ["Лиза", "Лизой"],
    ["Никита", "Никитой"], ["Любовь", "Любовью"], ["Дима", "Димой"], ["Саша", "Сашей"], ["Мария", "Марией"],
    ["Наталья", "Натальей"], ["Катя", "Катей"], ["Алина", "Алиной"], ["Олег", "Олегом"], ["Иван", "Иваном"],
    ["Алексей", "Алексеем"], ["Николай", "Николаем"], ["Василий", "Василием"], ["Игорь", "Игорем"], ["Ксюша", "Ксюшей"],
  ];
  for (const [name, want] of cases) assert.equal(instrumental(name), want, name);
});

test("творительный: сомнительное не склоняем", () => {
  for (const name of ["Адель", "Кармен", "Ники", "Марко", "Alex", "Артём Петров", "", "Тест 501", "Нинель", "Ким"]) {
    assert.equal(instrumental(name), null, name);
  }
});

test("родительный, винительный, дательный — как раньше", () => {
  assert.equal(genitive("Алина"), "Алины");
  assert.equal(genitive("Миша"), "Миши");
  assert.equal(genitive("Артём"), "Артёма");
  assert.equal(accusative("Алина"), "Алину");
  assert.equal(accusative("Артём"), "Артёма");
  assert.equal(dative("Лиза"), "Лизе");
  assert.equal(dative("Мария"), "Марии");
});
